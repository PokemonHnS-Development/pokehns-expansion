#!/usr/bin/env python3
"""Hoenn & Seek 2.0 (part 5): daily weather cycles.

Reads data/hoenn/weather_cycles.json and writes src/data/hoenn_weather_cycles.h, the
table src/hoenn_time.c looks maps up in (sorted by map ID, one entry per map). Each
entry is {MAP_*, WEATHER_*, offset, emerald}; the JSON's comment explains the fields.
Checks that every map exists and is listed once, and that offsets are 0-3.
"""
import json, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
P = lambda *a: os.path.join(ROOT, *a)


def main():
    cfg = json.load(open(P("data/hoenn/weather_cycles.json")))
    seen, rows = {}, []
    for g in cfg["groups"]:
        if not 0 <= g["offset"] <= 3:
            sys.exit("%s: offset must be 0-3" % g["name"])
        for name in g["maps"]:
            path = P("data/maps", name, "map.json")
            if not os.path.exists(path):
                sys.exit("%s: no map %s" % (g["name"], name))
            if name in seen:
                sys.exit("%s is in both %s and %s" % (name, seen[name], g["name"]))
            seen[name] = g["name"]
            mid = json.load(open(path))["id"]
            rows.append((mid, "WEATHER_" + g["weather"], g["offset"], bool(g.get("emerald")), g["name"]))
    out = ["// Generated by tools/hoenn/gen_hoenn_weather.py from data/hoenn/weather_cycles.json.",
           "// Do not edit by hand. Included by src/hoenn_time.c.", ""]
    for mid, w, off, em, gname in rows:
        out.append("    { %-28s %-26s %d, %-5s }, // %s" % (mid + ",", w + ",", off, "TRUE" if em else "FALSE", gname))
    open(P("src/data/hoenn_weather_cycles.h"), "w").write("\n".join(out) + "\n")
    print("%d maps in %d groups" % (len(rows), len(cfg["groups"])))


if __name__ == "__main__":
    main()
