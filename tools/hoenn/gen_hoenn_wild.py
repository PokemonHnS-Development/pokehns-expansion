#!/usr/bin/env python3
"""Hoenn & Seek (part 15): Hoenn wild encounters and items for HnS.

    tools/hoenn/gen_hoenn_wild.py

Reads data/hoenn/wild_rules.json and the Emerald tables in src/data/wild_encounters.json,
and writes data/hoenn/wild_encounters_hoenn.json: one day table (and a night table where
the rules give one) per kept Hoenn map, with levels on the map's band and species evolved
to fit. tools/wild_encounters/wild_encounters_to_header.py builds those for HnS instead of
the Emerald tables (which stay Emerald-only). It also upgrades item balls and hidden items
on kept maps (the "items" table), in place in their map.json.
"""
import copy, glob, json, os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
P = lambda *a: os.path.join(ROOT, *a)
FISH_DROP = 5


def level_evolutions():
    """SPECIES_X -> (level, SPECIES_Y) for species whose first evolution is EVO_LEVEL."""
    evo, cur = {}, None
    pat = re.compile(r"^\s*\[(SPECIES_\w+)\]\s*=|\.evolutions\s*=\s*EVOLUTION\(\s*\{(EVO_\w+),\s*([^,]+),\s*(SPECIES_\w+)", re.M)
    for path in sorted(glob.glob(P("src/data/pokemon/species_info/*.h"))):
        for m in pat.finditer(open(path).read()):
            if m.group(1):
                cur = m.group(1)
            elif cur and cur not in evo and m.group(2) == "EVO_LEVEL" and m.group(3).strip().isdigit():
                evo[cur] = (int(m.group(3)), m.group(4))
    return evo


def longest(prefixes, name):
    best = None
    for p in prefixes:
        if name.startswith(p) and (best is None or len(p) > len(best)):
            best = p
    return best


def apply_ops(entry, ops):
    for op in ops:
        if "swap" in op:
            for t, v in entry.items():
                if t.endswith("_mons"):
                    for mon in v["mons"]:
                        mon["species"] = op["swap"].get(mon["species"], mon["species"])
        else:
            mons = entry.get(op["type"], {}).get("mons", [])
            for i in op["slots"]:
                if i < len(mons):
                    mons[i]["species"] = op["species"]


def rescale(entry, band, evo):
    lo, hi = band
    for t, v in entry.items():
        if not t.endswith("_mons"):
            continue
        mons = v["mons"]
        tmin = min(m["min_level"] for m in mons)
        tmax = max(m["max_level"] for m in mons)
        blo = lo - FISH_DROP if t == "fishing_mons" else lo
        span = max(tmax - tmin, 1)
        f = lambda x: round(blo + (x - tmin) * (hi - blo) / span)
        for m in mons:
            a, b = f(m["min_level"]), f(m["max_level"])
            m["min_level"], m["max_level"] = min(a, b), max(a, b)
            while m["species"] in evo and evo[m["species"]][0] <= m["min_level"]:
                m["species"] = evo[m["species"]][1]


def main():
    rules = json.load(open(P("data/hoenn/wild_rules.json")))
    kept = json.load(open(P("data/hoenn/maps.json")))["items"]
    ids = {json.load(open(P("data/maps", m, "map.json")))["id"]: m for m in kept}
    evo = level_evolutions()
    enc = json.load(open(P("src/data/wild_encounters.json")))["wild_encounter_groups"][0]["encounters"]

    out, seen, missing = [], set(), []
    for e in enc:
        mid = e.get("map")
        if mid not in ids or "_hns" in e["base_label"].lower() or mid in seen:
            continue
        seen.add(mid)
        name = mid[len("MAP_"):]
        bp = longest(rules["bands"], name)
        if not bp:
            missing.append(name)
            continue
        rp = longest(rules["rules"], name)
        rule = rules["rules"].get(rp, {}) if rp else {}
        base = {k: v for k, v in e.items() if k.endswith("_mons")}
        label = "gHoenn_" + e["base_label"][1:] + "_hns"
        day = copy.deepcopy(base)
        apply_ops(day, rule.get("day", []))
        rescale(day, rules["bands"][bp], evo)
        out.append({"map": mid, "base_label": label, **day})
        if "night" in rule:
            night = copy.deepcopy(base)
            apply_ops(night, rule["night"])
            rescale(night, rules["bands"][bp], evo)
            out.append({"map": mid, "base_label": label + "_Night", **night})
    if missing:
        sys.exit("no level band for: " + ", ".join(missing))
    with open(P("data/hoenn/wild_encounters_hoenn.json"), "w") as f:
        json.dump({"_comment": "Generated by tools/hoenn/gen_hoenn_wild.py from data/hoenn/wild_rules.json. Do not edit.",
                   "encounters": out}, f, indent=1)
        f.write("\n")

    # ---- items
    items = {k: v for k, v in rules["items"].items() if k.startswith("ITEM_")}
    changed = 0
    for m in kept:
        path = P("data/maps", m, "map.json")
        raw = open(path).read()
        d = json.loads(raw)
        for o in d.get("object_events", []):
            if o.get("script") == "Common_EventScript_FindItem" and o["trainer_sight_or_berry_tree_id"] in items:
                o["trainer_sight_or_berry_tree_id"] = items[o["trainer_sight_or_berry_tree_id"]]
                changed += 1
        for b in d.get("bg_events", []):
            if b.get("type") == "hidden_item" and b["item"] in items:
                b["item"] = items[b["item"]]
                changed += 1
        new = json.dumps(d, indent=2, ensure_ascii=False) + "\n"
        if new != raw:
            open(path, "w").write(new)
    nights = sum(1 for x in out if x["base_label"].endswith("_Night"))
    print(f"{len(out) - nights} day tables, {nights} night tables, {changed} items upgraded")


if __name__ == "__main__":
    main()
