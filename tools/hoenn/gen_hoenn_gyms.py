#!/usr/bin/env python3
"""Write src/data/hoenn_gym_trainers.h: the Hoenn gym leaders (with rematch IDs) and
the trainers inside each gym, for the stamp-based level scaling in src/hoenn_scaling.c.
Gym maps are the kept Hoenn maps whose name contains '_Gym'."""
import json, os, re

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
def rd(p):
    with open(os.path.join(ROOT, p)) as f:
        return f.read()

LEADERS = ["ROXANNE", "BRAWLY", "WATTSON", "FLANNERY", "NORMAN", "WINONA", "TATE_AND_LIZA", "JUAN"]
maps = json.loads(rd("data/hoenn/maps.json"))["items"]
gyms = sorted(m for m in maps if "_Gym" in m)
opp = rd("include/constants/hoenn_trainers.h")
known = set(re.findall(r"#define (TRAINER_\w+)", opp))

leaders, trainers = [], set()
for m in gyms:
    for t in re.findall(r"\b(TRAINER_\w+)", rd(f"data/maps/{m}/scripts.inc")):
        if t.startswith("TRAINER_BATTLE_") or t not in known:
            continue
        if any(t.startswith(f"TRAINER_{l}_") for l in LEADERS):
            continue
        trainers.add(t)
for l in LEADERS:
    leaders += sorted(t for t in known if re.fullmatch(rf"TRAINER_{l}_\d", t))

out = ["// Generated by tools/hoenn/gen_hoenn_gyms.py. Do not edit.",
       f"// Gym maps: {', '.join(gyms)}",
       "static const u16 sHoennGymLeaders[] =", "{"]
out += [f"    {t}," for t in leaders] + ["};", "", "static const u16 sHoennGymTrainers[] =", "{"]
out += [f"    {t}," for t in sorted(trainers)] + ["};", ""]
with open(os.path.join(ROOT, "src/data/hoenn_gym_trainers.h"), "w") as f:
    f.write("\n".join(out))
print(f"hoenn_gym_trainers.h: {len(leaders)} leader IDs, {len(trainers)} gym trainers from {len(gyms)} maps")
