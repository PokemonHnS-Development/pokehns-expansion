#!/usr/bin/env python3
"""Generate the lists of Emerald (Hoenn) maps and layouts compiled into the
HnS build. tools/mapjson reads the output files.

    python3 tools/hoenn/gen_hoenn_lists.py

Inputs:  data/hoenn/exclude.json (cut rules, hand-edited), map.json files,
         data/layouts/layouts.json
Outputs: data/hoenn/maps.json, data/hoenn/layouts.json,
         data/hoenn/blocked_maps.json (generated, committed)

A kept map is any map.json tagged game_version "emerald" (the default) that:
  - is listed in data/maps/map_groups.json,
  - doesn't match an excluded exact name, prefix, or substring,
  - has no HnS copy named "<Name>_hns" (HnS already uses its own copy).
Kept layouts are the Emerald layouts used by at least one kept map, or swapped in by
a kept map's script (setmaplayoutindex).
"""
import glob
import json
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))


def load(path):
    with open(os.path.join(ROOT, path)) as f:
        return json.load(f)


def main():
    rules = load("data/hoenn/exclude.json")
    prefixes = tuple(rules["exclude_prefixes"])
    exact = set(rules["exclude_maps"])
    contains = tuple(rules.get("exclude_containing", []))

    groups = load("data/maps/map_groups.json")
    grouped = {m for g in groups["group_order"] for m in groups[g]}

    maps = {}
    for p in glob.glob(os.path.join(ROOT, "data/maps/*/map.json")):
        d = json.load(open(p))
        maps[d["name"]] = d
    names = set(maps)

    kept, reasons = [], {}
    for name, d in sorted(maps.items()):
        if d.get("game_version", "emerald") != "emerald":
            continue
        if name not in grouped:
            reasons[name] = "not in map_groups"
        elif name in exact or name.startswith(prefixes) or any(c in name for c in contains):
            reasons[name] = "excluded by rule"
        elif f"{name}_hns" in names:
            reasons[name] = "HnS has its own copy"
        else:
            kept.append(name)

    emerald_layouts = {
        l["id"] for l in load("data/layouts/layouts.json")["layouts"]
        if "id" in l and l.get("game_version", "emerald") == "emerald"
    }
    used = {maps[m]["layout"] for m in kept}
    # Also keep layouts that kept maps' scripts swap in at runtime (setmaplayoutindex),
    # e.g. Birch's lab with the Johto starter table, or Shoal Cave at high/low tide.
    import re as _re
    for m in kept:
        sp = os.path.join(ROOT, "data/maps", m, "scripts.inc")
        if os.path.exists(sp):
            used |= set(_re.findall(r"setmaplayoutindex (LAYOUT_\w+)", open(sp).read()))
    layouts = sorted(used & emerald_layouts)
    missing = sorted({maps[m]["layout"] for m in kept} - emerald_layouts)
    if missing:
        sys.exit(f"error: kept maps use non-Emerald layouts: {missing}")

    # Emerald maps that are NOT in the HnS build: tools/mapjson makes warps into
    # them unreachable in HnS (a door into a cut building stays shut, no crash).
    kept_set = set(kept)
    blocked = sorted(d["id"] for n, d in maps.items()
                     if d.get("game_version", "emerald") == "emerald" and n not in kept_set)

    header = "Generated by tools/hoenn/gen_hoenn_lists.py from data/hoenn/exclude.json. Do not edit."
    for fname, items in (("maps.json", kept), ("layouts.json", layouts), ("blocked_maps.json", blocked)):
        with open(os.path.join(ROOT, "data/hoenn", fname), "w") as f:
            json.dump({"_comment": header, "items": items}, f, indent=2)
            f.write("\n")

    by_reason = {}
    for n, r in reasons.items():
        by_reason.setdefault(r, []).append(n)
    print(f"kept maps: {len(kept)}   kept layouts: {len(layouts)}")
    for r, ns in sorted(by_reason.items()):
        print(f"  skipped ({r}): {len(ns)}")


if __name__ == "__main__":
    main()
