#!/usr/bin/env python3
"""Hoenn & Seek (2.0 part 25a): follow-the-lights routes.

    gen_hoenn_lights.py

Reads data/hoenn/light_paths.json. For each path, finds the shortest route over
passable blocks (collision 0) of the map's layout from `start` to `end`, puts a
stop every `spacing` steps plus one on `end` (a last hop shorter than half
`spacing` is merged into the one before), and writes
src/data/hoenn_light_paths.h (read by src/hoenn_lights.c). Checks that the
map's `local_id` object stands on `start`. Re-runs give the same file.

Optional keys (part 32, for lights on the sea's surface):
  "water_only": true     only blocks at elevation 1 (surf water) count as passable,
                         so the route never crosses a beach
  "avoid_objects": true  the tiles of the map's other objects (whirlpools,
                         swimmers, rocks you smash) are not passable either
"""
import json, os, struct
from collections import deque

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
P = lambda *a: os.path.join(ROOT, *a)
DIRS = [("DIR_NORTH", 0, -1), ("DIR_SOUTH", 0, 1), ("DIR_WEST", -1, 0), ("DIR_EAST", 1, 0)]


def route(lay, start, end, water_only=False, blocked=()):
    w, h = lay["width"], lay["height"]
    d = open(P(lay["blockdata_filepath"]), "rb").read()
    blocks = struct.unpack("<%dH" % (w * h), d)
    blocked = set(blocked)

    def free(x, y):
        if not (0 <= x < w and 0 <= y < h) or blocks[y * w + x] & 0x0C00 or (x, y) in blocked:
            return False
        return not water_only or blocks[y * w + x] >> 12 == 1
    assert free(*start) and free(*end), ("start/end blocked", start, end)
    prev = {tuple(start): None}
    q = deque([tuple(start)])
    while q:
        c = q.popleft()
        if c == tuple(end):
            break
        for name, dx, dy in DIRS:
            n = (c[0] + dx, c[1] + dy)
            if n not in prev and free(*n):
                prev[n] = (c, name)
                q.append(n)
    assert tuple(end) in prev, ("no route", start, end)
    steps, c = [], tuple(end)
    while prev[c]:
        c, name = prev[c]
        steps.append(name)
    return steps[::-1]


def main():
    spec = json.load(open(P("data/hoenn/light_paths.json")))
    lays = {l["id"]: l for l in json.load(open(P("data/layouts/layouts.json")))["layouts"] if "id" in l}
    out = ["// Generated by tools/hoenn/gen_hoenn_lights.py from data/hoenn/light_paths.json. Do not edit.",
           "// Included by src/hoenn_lights.c.", ""]
    for script in sorted({p["end_script"] for p in spec["paths"]}):
        out.append(f"extern const u8 {script}[];")
    out.append("")
    rows = []
    for p in spec["paths"]:
        m = json.load(open(P("data/maps", p["map"], "map.json")))
        objs = [o for o in m["object_events"] if o.get("local_id") == p["local_id"]]
        assert len(objs) == 1 and [objs[0]["x"], objs[0]["y"]] == p["start"], (p["name"], "light object must stand on start")
        blocked = []
        if p.get("avoid_objects"):
            blocked = [(o["x"], o["y"]) for o in m["object_events"] if o.get("local_id") != p["local_id"]]
        steps = route(lays[m["layout"]], p["start"], p["end"], p.get("water_only", False), blocked)
        idx = list(range(0, len(steps), p["spacing"]))
        if len(idx) > 1 and len(steps) - idx[-1] < p["spacing"] // 2:
            idx.pop()  # no short last hop: the stop before the end moves on to it
        idx.append(len(steps))
        x, y = p["start"]
        pos = [(x, y)]
        for name in steps:
            _, dx, dy = next(d for d in DIRS if d[0] == name)
            x, y = x + dx, y + dy
            pos.append((x, y))
        n = p["name"]
        out.append(f"// {n}: {len(steps)} steps, {len(idx)} stops")
        out.append(f"static const u8 sLightRoute_{n}[] = {{")
        for i in range(0, len(steps), 8):
            out.append("    " + ", ".join(steps[i:i + 8]) + ",")
        out.append("};")
        out.append(f"static const struct HoennLightStop sLightStops_{n}[] = {{")
        for i in idx:
            out.append(f"    {{{i}, {pos[i][0]}, {pos[i][1]}}},")
        out.append("};")
        out.append("")
        rows.append(f"    {{MAP_{m['id'][4:]}, {p['local_id']}, sLightRoute_{n}, sLightStops_{n}, ARRAY_COUNT(sLightStops_{n}), "
                    f"{p['near']}, {p['lost']}, {p['stage_var']}, {p['end_script']}}},")
    out.append("static const struct HoennLightPath sHoennLightPaths[] = {")
    out += rows
    out.append("};")
    open(P("src/data/hoenn_light_paths.h"), "w").write("\n".join(out) + "\n")
    for p in spec["paths"]:
        print(p["name"], "ok")


if __name__ == "__main__":
    main()
