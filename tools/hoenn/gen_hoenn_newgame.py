#!/usr/bin/env python3
"""Write data/scripts/hoenn_new_game.inc: the Hoenn part of the new-game flag reset.

It takes the flags Emerald sets in EventScript_ResetAllMapFlags (data/scripts/new_game.inc),
keeps only those that are Hoenn-owned in HnS (remapped by gen_hoenn_ids.py, so setting them
can't touch an HnS flag), then applies data/hoenn/newgame_overrides.json (post-Emerald state).
Re-run after gen_hoenn_ids.py or after editing the overrides."""
import json, os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
def rd(p):
    with open(os.path.join(ROOT, p)) as f:
        return f.read()

src = rd("data/scripts/new_game.inc")
block = src[src.index("EventScript_ResetAllMapFlags::"):src.index("EventScript_ResetAllMapFlagsHnS::")]
emerald = re.findall(r"^\s*setflag (\w+)", block, re.M)
report = json.loads(rd("data/hoenn/remap_report.json"))["flags"]
owned = lambda f: report.get(f, "").startswith("remapped")
keep = [f for f in emerald if owned(f)]
ov = json.loads(rd("data/hoenn/newgame_overrides.json"))
for f in ov.get("clear", []) + ov.get("set", []):
    if not owned(f):
        sys.exit(f"override {f} is not a Hoenn-owned flag (see data/hoenn/remap_report.json)")

out = ["@ Generated by tools/hoenn/gen_hoenn_newgame.py. Do not edit; edit data/hoenn/newgame_overrides.json.",
       "@ Run at new game after EventScript_ResetAllMapFlagsHnS (src/new_game.c).",
       "EventScript_ResetAllMapFlagsHoenn::",
       f"\t@ Emerald's new-game flags that Hoenn owns ({len(keep)} of {len(emerald)})"]
out += [f"\tsetflag {f}" for f in keep]
out.append("\t@ Post-Emerald state (data/hoenn/newgame_overrides.json)")
out += [f"\tclearflag {f}" for f in ov.get("clear", [])]
out += [f"\tsetflag {f}" for f in ov.get("set", [])]
out += ["\tend", ""]
with open(os.path.join(ROOT, "data/scripts/hoenn_new_game.inc"), "w") as f:
    f.write("\n".join(out))
print(f"hoenn_new_game.inc: {len(keep)} Emerald flags, {len(ov.get('clear', []))} cleared, {len(ov.get('set', []))} set")
