#!/usr/bin/env python3
"""Hoenn & Seek (part 20a): battle backgrounds for Hoenn maps.

Reads data/hoenn/battle_environments.json and writes src/data/hoenn_battle_environments.h,
which src/battle_setup.c includes at the end of sMapDefaultEnvironments. Maps in
"scene_normal" get battle_scene MAP_BATTLE_SCENE_NORMAL in their map.json.
"""
import json, os, re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
P = lambda *a: os.path.join(ROOT, *a)


def const(name):
    return "MAP_" + re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name).upper()


def main():
    cfg = json.load(open(P("data/hoenn/battle_environments.json")))
    kept = json.load(open(P("data/hoenn/maps.json")))["items"]
    rules = cfg["rules"]
    out = []
    for name in sorted(kept):
        if name in rules:
            env = rules[name]
        else:
            hits = [k for k in rules if k.endswith("_") and name.startswith(k)]
            env = rules[max(hits, key=len)] if hits else None
        if not env:
            continue
        m = json.load(open(P("data/maps", name, "map.json")))
        out.append(f"    {{{m['id']}, BATTLE_ENVIRONMENT_{env}}},")
    with open(P("src/data/hoenn_battle_environments.h"), "w") as f:
        f.write("// Generated by tools/hoenn/gen_hoenn_battle_bgs.py from data/hoenn/battle_environments.json.\n")
        f.write("// Included at the end of sMapDefaultEnvironments (src/battle_setup.c).\n")
        f.write("\n".join(out) + "\n")
    for name in cfg["scene_normal"]:
        path = P("data/maps", name, "map.json")
        s = open(path).read()
        s2 = re.sub(r'"battle_scene": "MAP_BATTLE_SCENE_\w+"', '"battle_scene": "MAP_BATTLE_SCENE_NORMAL"', s)
        if s2 != s:
            open(path, "w").write(s2)
    print(f"{len(out)} Hoenn maps with a battle background; {len(cfg['scene_normal'])} maps set to the normal scene")


if __name__ == "__main__":
    main()
