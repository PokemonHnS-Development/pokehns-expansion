#!/usr/bin/env python3
"""Hoenn & Seek (2.0 part 12): secret base spots at the reopened legendary sites.

Reads data/hoenn/base_spots.json and, for each spot:
  * writes the General tileset's closed cave indent (METATILE_General_<Colour>CaveIndent)
    into the map's layout .bin at x,y, with collision 1 and elevation 0 (what Emerald's
    own spots use), so Secret Power (MetatileBehavior_IsSecretBaseCave) accepts it and
    ToggleSecretBaseEntranceMetatile can open it;
  * adds (or updates) a "secret_base" bg event on that tile in the map's map.json, which is
    how SetOccupiedSecretBaseEntranceMetatiles reopens the player's base on later visits;
  * writes include/constants/hoenn_secret_bases.h with SECRET_BASE_HOENN_<NAME> = the
    group's first ID rounded down to the tens, plus the variant.

Every site's layout uses gTileset_General as its primary tileset (checked below), so the
indent metatiles exist there. Re-runs give the same result.
"""
import json, os, re, struct

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
P = lambda *a: os.path.join(ROOT, *a)

INDENT = {  # include/constants/metatile_labels.h
    "Red": 0x1A0,
    "Yellow": 0x1A8,
    "Blue": 0x1B0,
}


def group_base_ids():
    """SECRET_BASE_<GROUP>_1 -> its ID, from include/constants/secret_bases.h."""
    text = open(P("include/constants/secret_bases.h")).read()
    return {m.group(1): int(m.group(2)) for m in re.finditer(r"#define SECRET_BASE_(\w+)_1\s+(\d+)", text)}


def main():
    cfg = json.load(open(P("data/hoenn/base_spots.json")))
    kept = set(json.load(open(P("data/hoenn/maps.json")))["items"])
    layouts = {l["id"]: l for l in json.load(open(P("data/layouts/layouts.json")))["layouts"] if "id" in l}
    firsts = group_base_ids()
    defines = []
    for spot in cfg["spots"]:
        name, mapname = spot["name"], spot["map"]
        assert mapname in kept, f"{mapname} is not a kept Hoenn map"
        base_id = firsts[spot["group"]] // 10 * 10 + spot["variant"]
        assert 0 < base_id < 256 and 5 <= spot["variant"] <= 9, (name, base_id)
        const = f"SECRET_BASE_HOENN_{name}"
        defines.append(f"#define {const} {base_id}  // {spot['group']}, variant {spot['variant']}: {mapname} ({spot['x']},{spot['y']})")

        # Layout: put the closed indent on the wall tile.
        mpath = P("data/maps", mapname, "map.json")
        m = json.load(open(mpath))
        layout = layouts[m["layout"]]
        assert layout["primary_tileset"] == "gTileset_General", layout["id"]
        bin_path = P(layout["blockdata_filepath"])
        data = bytearray(open(bin_path, "rb").read())
        off = (spot["y"] * layout["width"] + spot["x"]) * 2
        struct.pack_into("<H", data, off, INDENT[spot["indent"]] | (1 << 10))  # collision 1, elevation 0
        open(bin_path, "wb").write(bytes(data))

        # map.json: one secret_base bg event on that tile.
        bgs = [b for b in m["bg_events"]
               if not (b["type"] == "secret_base" and b["x"] == spot["x"] and b["y"] == spot["y"])]
        bgs.append({"type": "secret_base", "x": spot["x"], "y": spot["y"], "elevation": 0, "secret_base_id": const})
        if bgs != m["bg_events"]:
            m["bg_events"] = bgs
            with open(mpath, "w") as f:
                json.dump(m, f, indent=2, ensure_ascii=False)
                f.write("\n")

    with open(P("include/constants/hoenn_secret_bases.h"), "w") as f:
        f.write("// Generated by tools/hoenn/gen_hoenn_base_spots.py from data/hoenn/base_spots.json.\n")
        f.write("// Secret base IDs for the spots at Hoenn's reopened legendary sites (2.0 part 12).\n")
        f.write("// An ID is group * 10 + variant; Emerald's own spots use variants 1-4.\n")
        f.write("#ifndef GUARD_CONSTANTS_HOENN_SECRET_BASES_H\n#define GUARD_CONSTANTS_HOENN_SECRET_BASES_H\n\n")
        f.write("\n".join(defines) + "\n\n#endif\n")
    print(f"{len(defines)} spots")


if __name__ == "__main__":
    main()
