def grid(s):
    return s.strip("\n").split("\n")


frames = [DOWN0, DOWN1, UP0, UP1, SIDE0, SIDE1]
sheet = Image.new("P", (192, 32), 0)
sheet.putpalette(pal)
for f, art in enumerate(frames):
    g = grid(art)
    h, w = len(g), len(g[0])
    ox, oy = f * 32 + (32 - w) // 2, 30 - h  # feet on the same row as the mother's
    for y, row in enumerate(g):
        assert len(row) == w, (f, y, row)
        for x, ch in enumerate(row):
            if ch != ".":
                sheet.putpixel((ox + x, oy + y), int(ch, 16))
column = Image.new("P", (32, 192), 0)
column.putpalette(pal)
for f in range(6):
    column.paste(sheet.crop((f * 32, 0, f * 32 + 32, 32)), (0, f * 32))
out = os.path.join(ROOT, "graphics/hoenn/kanga_baby/overworld.png")
os.makedirs(os.path.dirname(out), exist_ok=True)
column.save(out)
if "--preview" in sys.argv:
    big = Image.new("RGBA", (192 * 6, 32 * 12))
    big.paste(src.convert("RGBA").resize((192 * 6, 192), Image.NEAREST), (0, 0))
    big.paste(sheet.convert("RGBA").resize((192 * 6, 192), Image.NEAREST), (0, 192))
    big.save(sys.argv[sys.argv.index("--preview") + 1])
