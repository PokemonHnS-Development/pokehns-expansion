#!/usr/bin/env python3
"""Generate src/data/easy_chat/easy_chat_order_rtl.h: the Hebrew display order of each Easy Chat
word group (the group lists of the Easy Chat screen).

  gen_ec_order.py [--tree TREE] [--check]      TREE defaults to HNS_TREE; the header is rewritten there

A group list shows its words in the order of its .alphabeticalOrder fields, which upstream sorted
by the English texts. Under TEXT_RTL, src/easy_chat.c takes the order from this header instead, so
the group files keep the English fields and differ from the English baseline only in their texts.
Each group's words are sorted by their Hebrew text, as gen_dex_alpha.py sorts names (final forms
count as their base letter; geresh, gershayim, spaces and punctuation are ignored), then by the
text itself and by the word constant, so the order is stable. The species and move groups are
lists of names, not words, and are not reordered.

--check writes nothing. It regenerates the header in memory and compares it with the file: exit 0
when they are equal, exit 1 when the file is missing or stale (each group that differs is named).
"""
import argparse, os, re, sys

import paths
from gen_dex_alpha import key as hebrew_key

HEADER = os.path.join('src', 'data', 'easy_chat', 'easy_chat_order_rtl.h')
ENTRY = re.compile(r'\[EC_INDEX\(EC_WORD_(\w+)\)\]\s*=\s*\{\s*\.text\s*=\s*COMPOUND_STRING\("((?:[^"\\]|\\.)*)"\)')
TABLE = re.compile(r'const struct EasyChatWordInfo gEasyChatGroup_(\w+)\[\]')


def groups(tree):
    """[(array suffix, group file name, [(word, text)] in index order)] for the groups that hold words."""
    folder = os.path.join(tree, 'src', 'data', 'easy_chat')
    out = []
    for name in sorted(os.listdir(folder)):
        m = re.match(r'easy_chat_group_(\w+)\.h$', name)
        if not m:
            continue
        text = open(os.path.join(folder, name), encoding='utf-8').read()
        t = TABLE.search(text)
        if not t:
            continue
        body = text[t.end():]
        out.append((t.group(1), m.group(1), ENTRY.findall(body)))
    return out


def order(words):
    return [w for w, t in sorted(words, key=lambda wt: (hebrew_key(wt[1]), wt[1], wt[0]))]


def render(tree):
    parts = ['// The Hebrew alphabetical order of each Easy Chat word group, used by the group lists\n'
             '// under TEXT_RTL (src/easy_chat.c). Generated by tools/hebrew/gen_ec_order.py from the\n'
             '// word texts; run it again after changing a word.\n\n']
    table = []
    for suffix, name, words in groups(tree):
        parts.append('static const u16 sEasyChatRtlOrder_%s[] = {\n' % suffix)
        parts.extend('    EC_INDEX(EC_WORD_%s),\n' % w for w in order(words))
        parts.append('};\n\n')
        table.append('    [EC_GROUP_%s] = sEasyChatRtlOrder_%s,\n' % (name.upper(), suffix))
    parts.append('static const u16 *const sEasyChatRtlOrder[EC_NUM_GROUPS] = {\n')
    parts.extend(table)
    parts.append('};\n')
    return ''.join(parts)


def blocks(text):
    return dict(re.findall(r'static const u16 sEasyChatRtlOrder_(\w+)\[\] = \{\n(.*?)\};', text, re.S))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tree', default=paths.TREE)
    ap.add_argument('--check', action='store_true',
                    help='compare the header with a fresh generation; exit 1 if it is missing or stale')
    a = ap.parse_args()
    path = os.path.join(a.tree, HEADER)
    new = render(a.tree)
    if a.check:
        if not os.path.exists(path):
            print('gen_ec_order: %s is missing; run gen_ec_order.py' % HEADER)
            sys.exit(1)
        old = open(path, encoding='utf-8').read()
        if old == new:
            print('gen_ec_order: %d groups, the header is up to date' % len(blocks(new)))
            return
        ob, nb = blocks(old), blocks(new)
        for g in sorted(set(ob) | set(nb)):
            if ob.get(g) != nb.get(g):
                print('  %s: order differs' % g)
        print('gen_ec_order: %s is stale; run gen_ec_order.py and commit it' % HEADER)
        sys.exit(1)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(new)
    print('wrote %s: %d groups' % (HEADER, len(blocks(new))))


if __name__ == '__main__':
    main()
