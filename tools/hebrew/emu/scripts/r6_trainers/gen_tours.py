#!/usr/bin/env python3
"""gen_tours.py SRC TOURDIR: write the r6 field-trainer tours (r6t_*.txt) from trainerlist.py.

Tours: r6t_<region>_NN (johto_routes, kanto_routes, sinjoh_alola, gym_juniors; at most PER
trainers each), r6t_doubles (every double-battle object, then the one-Pokemon refusal once per
pair) and r6t_rematch_NN (the trainers whose script has a trainerbattle_rematch branch: first
battle, then the rematch). The first trainer of each class with a fixed facing and a sight of 2
or more is approached from 2-3 tiles out (`walk`), so the '!' and the walk-up are on screen."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import trainerlist  # noqa: E402

PER = 24
HEAD = """# r6 field trainers (generated by scripts/r6_trainers/gen_tours.py; run with r6trainers.py).
# %s
start saves/ladder6_postgame.sav
include ../r6_league/_base.txt
tbase
"""


def fixed(move):
    m = move.replace("MOVEMENT_TYPE_", "")
    return m in ("FACE_UP", "FACE_DOWN", "FACE_LEFT", "FACE_RIGHT")


def main(src, tdir):
    rows = trainerlist.build(src)
    os.makedirs(tdir, exist_ok=True)
    for p in os.listdir(tdir):
        if p.startswith("r6t_") and p.endswith(".txt"):
            os.remove(os.path.join(tdir, p))
    walk = set()
    seen = set()
    for r in rows:
        if r["kind"] == "single" and fixed(r["move"]) and r["sight"] >= 2 and r["class"] not in seen:
            seen.add(r["class"])
            walk.add((r["map"], r["local"]))
    singles = [r for r in rows if r["kind"] == "single"]
    n = 0
    for reg in ("johto_routes", "kanto_routes", "sinjoh_alola", "gym_juniors"):
        rr = [r for r in singles if r["region"] == reg]
        for k in range(0, len(rr), PER):
            ch = rr[k:k + PER]
            name = "r6t_%s_%02d.txt" % (reg, k // PER + 1)
            with open(os.path.join(tdir, name), "w") as fh:
                fh.write(HEAD % ("%s, trainers %d-%d of %d" % (reg, k + 1, k + len(ch), len(rr))))
                for r in ch:
                    opt = " walk" if (r["map"], r["local"]) in walk else ""
                    fh.write("trainer %s %d%s\n" % (r["map"], r["local"], opt))
                    n += 1
    dbl = [r for r in rows if r["kind"] == "double"]
    with open(os.path.join(tdir, "r6t_doubles.txt"), "w") as fh:
        fh.write(HEAD % "double battles: each twin object, then the refusal with one usable Pokemon")
        for r in dbl:
            fh.write("trainer %s %d\n" % (r["map"], r["local"]))
        done = set()
        for r in dbl:
            if r["trainer"] not in done:
                done.add(r["trainer"])
                fh.write("trainer %s %d notenough\n" % (r["map"], r["local"]))
    rem = [r for r in rows if r["rematch"]]
    for k in range(0, len(rem), 20):
        ch = rem[k:k + 20]
        with open(os.path.join(tdir, "r6t_rematch_%02d.txt" % (k // 20 + 1)), "w") as fh:
            fh.write(HEAD % "rematches: first battle, trainerRematches[tableId] = 1, the rematch")
            for r in ch:
                fh.write("trainer %s %d rematch\n" % (r["map"], r["local"]))
    print("%d singles, %d double objects, %d rematch, %d walk" % (n, len(dbl), len(rem), len(walk)))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
