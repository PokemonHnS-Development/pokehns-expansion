#!/usr/bin/env python3
"""Write ofui_phone.txt: every trainer that a map script registers with `register_matchcall`
(data/maps/*_hns/scripts.inc) goes into the PokeGear phone list. Most are set with the special
the macro uses (setvar VAR_0x8004; special SetMatchCallRegisteredFlag,
src/pokenav_match_call_data.c:1689-1694, asm/macros/event.inc:2195-2200); three go through the
full macro, which shows "Registered X in the PokeGear" (Std_RegisteredInMatchCall,
data/scripts/trainer_script.inc:1-11): the widest class + name (Beverly), a class with the
female sign (Nicole) and Jose. Then POKEGEAR > CALL: the list row by row to its end and back,
a trainer's CALL / CHECK / CANCEL box, the CHECK page, and a call from the list.

    gen_phone.py SRC_TREE > ofui_phone.txt
"""
import glob
import re
import sys

src = sys.argv[1]
names = set()
for p in glob.glob("%s/data/maps/*_hns/scripts.inc" % src):
    names.update(re.findall(r"register_matchcall\s+(TRAINER_\w+)", open(p, encoding="utf-8").read()))
names = sorted(names)
msg = ["TRAINER_BEVERLY_HNS", "TRAINER_NICOLE_HNS", "TRAINER_JOSE_HNS"]
quiet = [n for n in names if n not in msg]
out = ["# Generated by gen_phone.py (%d trainers)." % len(names),
       "start saves/ofui_menuA_base.sav",
       "include ../continue.txt",
       "go DOWN 9                  # Cherrygrove City: calls work only where Fly works",
       "waitctl 600"]
for i in range(0, len(quiet), 8):
    body = "; ".join("setvar VAR_0x8004, %s; special SetMatchCallRegisteredFlag" % n for n in quiet[i:i + 8])
    out.append("ev %s; end" % body)
for n in msg:
    short = n[len("TRAINER_"):-len("_HNS")].lower()
    out.append("evstart lockall; register_matchcall %s; releaseall; end" % n)
    out.append("talk phone_reg_%s 4 -" % short)
out += ["startmenu POKEGEAR",
        "waitcb2x CB2_Pokenav 600",
        "waitnav",
        "press DOWN",
        "waitnav",
        "press DOWN",
        "waitnav",
        "snap phone_00_menu_call",
        "press A",
        "waitnav",
        "snap phone_list_00"]
for i in range(1, len(names) + 4):
    out += ["press DOWN", "waitnav", "snap phone_list_%02d" % i]
# back to the top with page jumps (LEFT/RIGHT page the list in the PokeNav)
out += ["press LEFT", "waitnav", "snap phone_list_page_up_1",
        "press LEFT", "waitnav", "snap phone_list_page_up_2",
        "press RIGHT", "waitnav", "snap phone_list_page_down_1"]
# a trainer row: A = CALL / CANCEL. H&S trainers have no CHECK page
# (MatchCall_HasCheckPage_Trainer returns FALSE under IS_HNS, src/pokenav_match_call_data.c:1433-1438).
def call(tag):
    return ["press A", "waitnav", "snap phone_%s_opts_call" % tag,
            "press DOWN", "waitnav", "snap phone_%s_opts_cancel" % tag,
            "press UP", "waitnav",
            "press A",
            "pages phone_%s_call 30" % tag,
            "snap phone_%s_call_end" % tag,
            "press A", "waitnav", "snap phone_%s_after" % tag]
out += call("a")
out += ["press DOWN", "waitnav", "press DOWN", "waitnav", "press DOWN", "waitnav", "snap phone_b_row"]
out += call("b")
out += ["press UP", "waitnav", "press UP", "waitnav", "press UP", "waitnav", "press UP", "waitnav",
        "press UP", "waitnav", "snap phone_c_row"]
out += call("c")
print("\n".join(out))
