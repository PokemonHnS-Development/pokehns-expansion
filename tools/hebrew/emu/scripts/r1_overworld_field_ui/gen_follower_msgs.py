#!/usr/bin/env python3
"""Write ofui_follower_msgs.txt: every follower message (the basic pools in
src/data/text/follower_messages.h and the conditional sCondMsgNN in src/follower_helper.c),
shown in the field message box the way EventScript_FollowerGeneric shows it
(data/scripts/follower.inc: message, waitmessage, waitbuttonpress), with STR_VAR_1 set to
the widest Hebrew species name (Meowscarada, 60 px in FONT_NORMAL by textwidth.py).

    gen_follower_msgs.py SRC_TREE > ofui_follower_msgs.txt
"""
import re
import sys

src = sys.argv[1]
names = []
for rel in ("src/data/text/follower_messages.h", "src/follower_helper.c"):
    for m in re.finditer(r"static const u8 (s[A-Za-z]+Msg\d+)\[\]", open("%s/%s" % (src, rel), encoding="utf-8").read()):
        names.append(m.group(1))
print("# Generated by gen_follower_msgs.py: %d follower messages, one message box each." % len(names))
print("start saves/ofui_menuA_base.sav")
print("include ../continue.txt")
print("go DOWN 9")
print("waitctl 600")
for n in names:
    print("evstart lockall; bufferspeciesname STR_VAR_1, SPECIES_MEOWSCARADA; message 0x@%s@; waitmessage; waitbuttonpress; releaseall; end" % n)
    print("talk fm_%s 3 -" % n)
