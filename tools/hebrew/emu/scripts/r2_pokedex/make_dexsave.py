#!/usr/bin/env python3
"""Write the event scripts and ladder scripts that mark the Pokedex for the r2 dex sweep.

    make_dexsave.py [SRC]        SRC = the source tree whose include/constants/pokedex.h is read
                                 (default HNS_SRC, else the tree two levels above tools/hebrew)

Writes next to this file:
  dex_all_N.inc / dexsave_all.txt       every national number 1..NATIONAL_DEX_COUNT seen and caught
  dex_mixed_N.inc / dexsave_mixed.txt   every number seen and caught, except SEEN_ONLY (seen, not
                                        caught) and UNSEEN (neither)
Each species is marked with setcaughtmon SPECIES_X (which also sets the seen flag,
src/scrcmd.c Scrcmd_getsetpokedexflag) or setseenmon; NATIONAL_DEX_X -> SPECIES_X, with the
exceptions in RENAME. The scripts are split in chunks that fit evasm's RAM buffer
(gRfuAPIBuffer, 0xE64 bytes; 6 bytes per command).

Build a save (ladder.py, a copy of ladder6_postgame, the game's own save at the end):
    ladder.py run dexsave_all.txt OUT --save ladder6_postgame.sav --save-out dex_all.sav
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("HNS_SRC") or os.path.abspath(
    os.path.join(HERE, "..", "..", "..", "..", ".."))
RENAME = {"TAUROS_PALDEA": "TAUROS_PALDEA_COMBAT"}
# Seen but not caught: the INFO page's unknown category, height and weight; the list's empty
# ball; no STATS page. A base form with evolutions (Ivysaur, Metapod), a regional form, a single
# stage, the last entry of the obtainable list, a mythical.
SEEN_ONLY = ["IVYSAUR", "METAPOD", "RATTATA_ALOLA", "WOBBUFFET", "NOIVERN", "MEW"]
# Never seen: a gap in the national list and an unseen target on Charmander's EVO page.
UNSEEN = ["CHARMELEON"]
CHUNK = 400


def national_names(src):
    text = open(os.path.join(src, "include", "constants", "pokedex.h"), encoding="utf-8").read()
    body = text[text.index("enum NationalDexOrder"):]
    body = body[:body.index("};")]
    names = re.findall(r"\bNATIONAL_DEX_([A-Z0-9_]+)", body)
    return [n for n in names if n != "NONE"]


def write(kind, names):
    lines = []
    for n in names:
        sp = "SPECIES_" + RENAME.get(n, n)
        if kind == "mixed" and n in UNSEEN:
            continue
        if kind == "mixed" and n in SEEN_ONLY:
            lines.append("\tsetseenmon %s" % sp)
        else:
            lines.append("\tsetcaughtmon %s" % sp)
    files = []
    for i in range(0, len(lines), CHUNK):
        f = "dex_%s_%d.inc" % (kind, i // CHUNK + 1)
        with open(os.path.join(HERE, f), "w") as fh:
            fh.write("@ generated by make_dexsave.py (%s)\n" % kind)
            fh.write("\n".join(lines[i:i + CHUNK]) + "\n\tend\n")
        files.append(f)
    with open(os.path.join(HERE, "dexsave_%s.txt" % kind), "w") as fh:
        fh.write("# Pokedex marks for the r2 dex sweep (%s), generated by make_dexsave.py.\n" % kind)
        fh.write("# ladder.py run dexsave_%s.txt OUT --save <copy of ladder6_postgame.sav> "
                 "--save-out dex_%s.sav\n" % (kind, kind))
        fh.write("include ../continue.txt\n")
        for f in files:
            fh.write("event %s\n" % f)
        fh.write("savegame\nshot dexsave_%s_saved\n" % kind)
    return files


if __name__ == "__main__":
    names = national_names(SRC)
    print("%d national numbers in %s" % (len(names), SRC))
    for kind in ("all", "mixed"):
        print(kind, write(kind, names))
