#!/usr/bin/env python3
"""gen_classes.py SRC > _classes.txt: one `ptalk` line per partner text table
(sPartnerTrainerTextTables, src/battle_tower.c), in table order, each with the first frontier
trainer of that facility class (src/data/battle_frontier/battle_frontier_trainers.h). Both Pokemon
are fixed so the Hebrew and English runs show the same names: frontier mon 236 (Hitmontop, Triple
Kick: the widest Hebrew species + move pair) and 57 (Pineco, Self-Destruct: the widest move)."""
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "."
consts = {}
for line in open(src + "/include/constants/battle_frontier_trainers.h"):
    m = re.match(r"#define (FRONTIER_TRAINER_\w+)\s+(\d+)", line)
    if m:
        consts[m.group(1)] = int(m.group(2))
data = open(src + "/src/data/battle_frontier/battle_frontier_trainers.h", encoding="utf-8").read()
first = {}
for name, cls in re.findall(r"\[(FRONTIER_TRAINER_\w+)\]\s*=\s*\{\s*\.facilityClass\s*=\s*(\w+)", data):
    i = consts[name]
    if cls not in first or i < first[cls]:
        first[cls] = i
bt = open(src + "/src/battle_tower.c", encoding="utf-8").read()
table = re.search(r"sPartnerTrainerTextTables\[\]\s*=\s*\{(.*?)\};", bt, re.S).group(1)
print("# generated by gen_classes.py: one partner text table per line (K=4: the candidate at (10,11))")
for n, (cls, tab) in enumerate(re.findall(r"\{(FACILITY_CLASS_\w+),\s*(sPartnerTexts\w+)\}", table), 1):
    print("ptalk c%02d_%s 4 %d 236 57" % (n, tab.replace("sPartnerTexts", "").lower(), first[cls]))
