#!/usr/bin/env python3
"""Generate the 'one-time' move tutor tours (tours/t1*_once_*.txt). In Heart & Soul these tutors are
NOT one-time: include/constants/flags_hns.h:1597-1606 defines every FLAG_MOVE_TUTOR_TAUGHT_* as 0, so
the move_tutor macro (asm/macros/event.inc:2747) leaves out the flag check, the 'This move can only be
learned once' YES/NO and the setflag (checked in the rc5 ROM bytes of the Swagger tutor). Each tour:
teach YES/NO answered NO (declined text); YES, the box, the party pane, Golem (party slot 1, 2 moves)
learns the move at once, the taught text; talking again starts over (teach YES/NO, NO). Dynamic Punch
also teaches Typhlosion (4 moves) through the summary, for the longest move name.
Run: python3 gen.py"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
# key, map, stand x, y, face, npc local id + fixed x y if it wanders, flag, label
TUTORS = [
    ("rollout", "MAP_PEWTER_CITY_HNS", 27, 16, "UP", (9, 27, 15), "FLAG_MOVE_TUTOR_TAUGHT_ROLLOUT",
     "MauvilleCity_EventScript_RolloutTutor (PewterCity_hns object 9)"),
    ("metronome", "MAP_OLIVINE_CITY_HNS", 28, 42, "UP", (23, 28, 41), "FLAG_MOVE_TUTOR_TAUGHT_METRONOME",
     "FallarborTown_Mart_EventScript_MetronomeTutor (OlivineCity_hns object 23)"),
    ("dynpunch", "MAP_ROUTE4_HNS", 50, 4, "UP", None, "FLAG_MOVE_TUTOR_TAUGHT_DYNAMICPUNCH",
     "MossdeepCity_EventScript_DynamicPunchTutor (Route4_hns object 11)"),
    ("swagger", "MAP_ROUTE4_POKEMON_CENTER_HNS", 12, 6, "UP", None, "FLAG_MOVE_TUTOR_TAUGHT_SWAGGER",
     "SlateportCity_PokemonFanClub_EventScript_SwaggerTutor (Route4_PokemonCenter_hns object 3)"),
    ("mimic", "MAP_SAFFRON_CITY_POKEMON_CENTER_HNS", 2, 6, "LEFT", None, "FLAG_MOVE_TUTOR_TAUGHT_MIMIC",
     "LavaridgeTown_House_EventScript_MimicTutor (SaffronCity_PokemonCenter_hns object 6)"),
    ("substitute", "MAP_GATE_ROUTE40_TRAINER_HILL_COURTYARD_HNS", 9, 5, "UP", None, "FLAG_MOVE_TUTOR_TAUGHT_SUBSTITUTE",
     "LilycoveCity_DepartmentStoreRooftop_EventScript_SubstituteTutor (Gate_Route40_TrainerHill_Courtyard_hns object 1)"),
    ("furycutter", "MAP_ILEX_FOREST_HNS", 24, 15, "UP", None, "FLAG_MOVE_TUTOR_TAUGHT_FURY_CUTTER",
     "VerdanturfTown_PokemonCenter_1F_EventScript_FuryCutterTutor (IlexForest_hns object 36)"),
]


def approach(t):
    key, mp, x, y, face, fix, flag, label = t
    out = []
    if fix:
        lid, nx, ny = fix
        # a wandering NPC: reload the map, freeze it where it stops, walk below it
        out += ["warpto %s %d %d" % (mp, x, y), "approachnpc %d" % lid]
        return out
    out.append("face %s" % face)
    return out


def tour(i, t):
    key, mp, x, y, face, fix, flag, label = t
    p = "o%s" % key[:4]
    L = ["# 'One-time' tutor (repeatable in H&S, see ../gen.py): %s. Generated by ../gen.py." % label,
         "start saves/ladder6_postgame_copy.sav",
         "include _setup.txt",
         ]
    L += approach(t) if fix else ["warpto %s %d %d" % (mp, x, y)] + approach(t)
    L += ["# --- 1. NO", "talk %s1_teach 10" % p, "tap B 0", "talk %s1_declined 10 -" % p, "waitctl 900"]
    L += approach(t)
    L += ["# --- 3. YES, Golem", "talk %s3_teach 10" % p, "tap A 0",
          "talk %s3_which 10 -" % p, "include _pickparty.txt", "snap %s3_box" % p, "boxgo 1 0",
          "snap %s3_party" % p, "boxpick 1 1 %s3_party_golem" % p, "include _tofield.txt",
          "pages %s3_learned 1" % p, "talk %s3_taught 10 -" % p, "waitctl 900"]
    L += approach(t)
    L += ["# --- 4. again: the tutor starts over (no flag in H&S)", "talk %s4_again 10" % p, "tap B 0",
          "talk %s4_declined 10 -" % p, "waitctl 900"]
    if key == "dynpunch":
        L += ["# --- 5. Typhlosion (4 moves) through the summary"]
        L += approach(t)
        L += ["talk %s5_teach 10" % p, "tap A 0",
              "talk %s5_which 10 -" % p, "include _pickparty.txt", "boxpick 1 0", "include _tofield.txt",
              "pages %s5_replace 2" % p, "waitlearn 5", "snap %s5_replace_yesno" % p, "tap A 0",
              "pages %s5_whichforget 1" % p, "waitcb2x pokemon_summary_screen:MainCB2 900",
              "waittaskx pokemon_summary_screen:Task_HandleReplaceMoveInput 900", "waitquiet",
              "press UP", "snap %s5_summary_new" % p, "press UP", "snap %s5_summary_4" % p, "press A",
              "waitcb2x CB2_Overworld 900", "waittaskx field_specials:Task_LearnMove 900",
              "pages %s5_poof 4" % p, "talk %s5_taught 10 -" % p, "waitctl 900"]
    return "\n".join(L) + "\n"


for i, t in enumerate(TUTORS):
    path = os.path.join(HERE, "tours", "t1%d_once_%s.txt" % (i, t[0]))
    open(path, "w").write(tour(i, t))
    print(path)
